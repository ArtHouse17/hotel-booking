CREATE TABLE hotels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    address VARCHAR(300) NOT NULL
);

CREATE TABLE rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id BIGINT NOT NULL REFERENCES hotels(id),
    number VARCHAR(30) NOT NULL,
    available BOOLEAN NOT NULL DEFAULT TRUE,
    times_booked BIGINT NOT NULL DEFAULT 0 CHECK (times_booked >= 0),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_room_number UNIQUE (hotel_id, number)
);

CREATE TABLE room_reservations (
    booking_id UUID PRIMARY KEY,
    room_id BIGINT NOT NULL REFERENCES rooms(id),
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    active BOOLEAN NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_reservation_dates CHECK (end_date > start_date)
);

CREATE INDEX idx_slot_overlap ON room_reservations(room_id, active, start_date, end_date);
