CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(60) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(16) NOT NULL CHECK (role IN ('USER', 'ADMIN'))
);

CREATE TABLE bookings (
    id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    request_id UUID NOT NULL,
    fingerprint VARCHAR(255) NOT NULL,
    room_id BIGINT,
    hotel_id BIGINT,
    auto_select BOOLEAN NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('PENDING', 'CONFIRMED', 'CANCELLED')),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    compensation_required BOOLEAN NOT NULL DEFAULT FALSE,
    failure_reason VARCHAR(255),
    failure_status INTEGER,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_booking_request UNIQUE (user_id, request_id),
    CONSTRAINT ck_booking_dates CHECK (end_date > start_date)
);

CREATE INDEX idx_booking_owner ON bookings(user_id, created_at);
